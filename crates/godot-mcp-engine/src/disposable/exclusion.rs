//! What never enters a disposable copy, and why.
//!
//! The policy is deliberately **explicit and enumerable** rather than clever. A
//! copy that silently admitted a credential file would hand that credential to
//! code that is about to execute, and a copy that admitted `.godot/` would hand
//! the untrusted run a pre-seeded engine cache — including Godot's own copy of
//! `project.godot` written *inside* that cache, which is engine state and never
//! source.
//!
//! Every decision this module makes is reported, not just applied: an excluded
//! entry appears in the copy manifest with the [`ExclusionReason`] that kept it
//! out. A caller can therefore see what was withheld instead of inferring it
//! from an absence.
//!
//! This module decides *what is copied*. It is not a sandbox and does not claim
//! to be: excluding a file from the copy does not stop project code from reading
//! the original — see [`crate::disposable::posture`].

use std::collections::BTreeSet;

/// Why an entry was kept out of a disposable copy.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ExclusionReason {
    /// Credential, key or token material. Never handed to code that will run.
    SecretMaterial,
    /// Engine-generated cache/state, regenerated by the run itself.
    EngineGeneratedCache,
    /// Version-control metadata: history, remotes and stored credentials.
    VersionControlMetadata,
    /// Build output and other regenerable artifacts.
    BuildOutput,
    /// The operator named this path explicitly.
    OperatorRequested,
}

impl ExclusionReason {
    /// Every reason. There are five.
    pub const ALL: [Self; 5] = [
        Self::SecretMaterial,
        Self::EngineGeneratedCache,
        Self::VersionControlMetadata,
        Self::BuildOutput,
        Self::OperatorRequested,
    ];

    /// Stable wire spelling recorded in a copy manifest.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::SecretMaterial => "secret_material",
            Self::EngineGeneratedCache => "engine_generated_cache",
            Self::VersionControlMetadata => "version_control_metadata",
            Self::BuildOutput => "build_output",
            Self::OperatorRequested => "operator_requested",
        }
    }

    /// Parse the canonical wire spelling.
    #[must_use]
    pub fn parse(text: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|reason| reason.as_str() == text)
    }
}

/// Directory names never copied, with the reason each is refused.
///
/// `.godot` is the load-bearing entry. It is the engine's cache, it is
/// regenerated by the very import that would read it, and it contains Godot's own
/// copy of `project.godot` — a file a naive upward project search would mistake
/// for a project root.
pub const EXCLUDED_DIRECTORIES: [(&str, ExclusionReason); 6] = [
    (".godot", ExclusionReason::EngineGeneratedCache),
    (".import", ExclusionReason::EngineGeneratedCache),
    (".git", ExclusionReason::VersionControlMetadata),
    (".svn", ExclusionReason::VersionControlMetadata),
    (".hg", ExclusionReason::VersionControlMetadata),
    ("android/build", ExclusionReason::BuildOutput),
];

/// Exact file names never copied.
///
/// `export_presets.cfg` is here because Godot's export dialog stores Android
/// keystore and store credentials in it, which is why the manual recommends
/// keeping it out of version control.
pub const EXCLUDED_FILE_NAMES: [(&str, ExclusionReason); 12] = [
    (".env", ExclusionReason::SecretMaterial),
    (".netrc", ExclusionReason::SecretMaterial),
    (".npmrc", ExclusionReason::SecretMaterial),
    ("credentials", ExclusionReason::SecretMaterial),
    ("credentials.json", ExclusionReason::SecretMaterial),
    ("secrets.json", ExclusionReason::SecretMaterial),
    ("secrets.toml", ExclusionReason::SecretMaterial),
    ("secrets.yaml", ExclusionReason::SecretMaterial),
    ("secrets.yml", ExclusionReason::SecretMaterial),
    ("id_rsa", ExclusionReason::SecretMaterial),
    ("id_ed25519", ExclusionReason::SecretMaterial),
    ("export_presets.cfg", ExclusionReason::SecretMaterial),
];

/// File-name prefixes never copied. `.env.production`, `.env.local` and friends.
pub const EXCLUDED_FILE_PREFIXES: [(&str, ExclusionReason); 1] =
    [(".env.", ExclusionReason::SecretMaterial)];

/// File-name suffixes never copied.
pub const EXCLUDED_FILE_SUFFIXES: [(&str, ExclusionReason); 7] = [
    (".pem", ExclusionReason::SecretMaterial),
    (".key", ExclusionReason::SecretMaterial),
    (".p12", ExclusionReason::SecretMaterial),
    (".pfx", ExclusionReason::SecretMaterial),
    (".keystore", ExclusionReason::SecretMaterial),
    (".jks", ExclusionReason::SecretMaterial),
    (".env", ExclusionReason::SecretMaterial),
];

/// The set of names that keep material out of a disposable copy.
///
/// Cloneable and comparable so a caller can prove two copies were made under the
/// same policy — which is half of the determinism claim.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExclusionPolicy {
    extra_directories: BTreeSet<String>,
    extra_files: BTreeSet<String>,
}

impl Default for ExclusionPolicy {
    fn default() -> Self {
        Self::new()
    }
}

impl ExclusionPolicy {
    /// The built-in policy: secrets, engine cache, VCS metadata, build output.
    #[must_use]
    pub fn new() -> Self {
        Self {
            extra_directories: BTreeSet::new(),
            extra_files: BTreeSet::new(),
        }
    }

    /// Also exclude a project-relative directory the operator named.
    #[must_use]
    pub fn excluding_directory(mut self, relative: &str) -> Self {
        self.extra_directories.insert(normalize(relative));
        self
    }

    /// Also exclude a project-relative file the operator named.
    #[must_use]
    pub fn excluding_file(mut self, relative: &str) -> Self {
        self.extra_files.insert(normalize(relative));
        self
    }

    /// The operator-named directories, sorted.
    #[must_use]
    pub fn operator_directories(&self) -> Vec<String> {
        self.extra_directories.iter().cloned().collect()
    }

    /// The operator-named files, sorted.
    #[must_use]
    pub fn operator_files(&self) -> Vec<String> {
        self.extra_files.iter().cloned().collect()
    }

    /// Whether a project-relative directory is excluded, and why.
    ///
    /// `relative` is slash-separated and never starts with a separator. Both the
    /// full relative path and the final component are considered, so `.git` is
    /// refused wherever it appears rather than only at the root.
    #[must_use]
    pub fn directory_verdict(&self, relative: &str) -> Option<ExclusionReason> {
        let relative = normalize(relative);
        if self.extra_directories.contains(&relative) {
            return Some(ExclusionReason::OperatorRequested);
        }
        let component = last_component(&relative);
        EXCLUDED_DIRECTORIES
            .into_iter()
            .find(|(name, _)| *name == relative || *name == component)
            .map(|(_, reason)| reason)
    }

    /// Whether a project-relative file is excluded, and why.
    #[must_use]
    pub fn file_verdict(&self, relative: &str) -> Option<ExclusionReason> {
        let relative = normalize(relative);
        if self.extra_files.contains(&relative) {
            return Some(ExclusionReason::OperatorRequested);
        }
        let name = last_component(&relative);
        if let Some((_, reason)) = EXCLUDED_FILE_NAMES
            .into_iter()
            .find(|(entry, _)| *entry == name)
        {
            return Some(reason);
        }
        if let Some((_, reason)) = EXCLUDED_FILE_PREFIXES
            .into_iter()
            .find(|(prefix, _)| name.starts_with(prefix))
        {
            return Some(reason);
        }
        if let Some((_, reason)) = EXCLUDED_FILE_SUFFIXES
            .into_iter()
            .find(|(suffix, _)| name.len() > suffix.len() && name.ends_with(suffix))
        {
            return Some(reason);
        }
        None
    }

    /// Every rule this policy enforces, as `(pattern, reason)` pairs, sorted.
    /// Callers render this into a manifest so the policy itself is auditable.
    #[must_use]
    pub fn rules(&self) -> Vec<(String, ExclusionReason)> {
        let mut rules: Vec<(String, ExclusionReason)> = Vec::new();
        for (name, reason) in EXCLUDED_DIRECTORIES {
            rules.push((format!("dir:{name}"), reason));
        }
        for (name, reason) in EXCLUDED_FILE_NAMES {
            rules.push((format!("name:{name}"), reason));
        }
        for (prefix, reason) in EXCLUDED_FILE_PREFIXES {
            rules.push((format!("prefix:{prefix}"), reason));
        }
        for (suffix, reason) in EXCLUDED_FILE_SUFFIXES {
            rules.push((format!("suffix:{suffix}"), reason));
        }
        for name in &self.extra_directories {
            rules.push((format!("dir:{name}"), ExclusionReason::OperatorRequested));
        }
        for name in &self.extra_files {
            rules.push((format!("name:{name}"), ExclusionReason::OperatorRequested));
        }
        rules.sort();
        rules
    }
}

fn normalize(relative: &str) -> String {
    relative.replace('\\', "/").trim_matches('/').to_lowercase()
}

fn last_component(relative: &str) -> String {
    relative.rsplit('/').next().unwrap_or(relative).to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_engine_cache_is_excluded_wherever_it_appears() {
        let policy = ExclusionPolicy::default();
        assert_eq!(
            policy.directory_verdict(".godot"),
            Some(ExclusionReason::EngineGeneratedCache)
        );
        assert_eq!(
            policy.directory_verdict("nested/.godot"),
            Some(ExclusionReason::EngineGeneratedCache),
            "a nested engine cache is still engine state"
        );
        assert_eq!(policy.directory_verdict("scripts"), None);
    }

    #[test]
    fn version_control_metadata_is_excluded_by_directory_not_by_file() {
        let policy = ExclusionPolicy::default();
        assert_eq!(
            policy.directory_verdict(".git"),
            Some(ExclusionReason::VersionControlMetadata)
        );
        assert_eq!(
            policy.file_verdict(".gitignore"),
            None,
            "`.gitignore` is ordinary project content, not VCS internals"
        );
    }

    #[test]
    fn secret_material_is_matched_by_name_prefix_and_suffix() {
        let policy = ExclusionPolicy::default();
        for path in [
            ".env",
            ".env.production",
            "private.pem",
            "release.keystore",
            "credentials.json",
            "export_presets.cfg",
            "config/service.key",
        ] {
            assert_eq!(
                policy.file_verdict(path),
                Some(ExclusionReason::SecretMaterial),
                "{path} must be treated as secret material"
            );
        }
        assert_eq!(policy.file_verdict("project.godot"), None);
        assert_eq!(policy.file_verdict("scripts/player.gd"), None);
    }

    #[test]
    fn a_bare_suffix_name_is_not_mistaken_for_a_suffix_match() {
        let policy = ExclusionPolicy::default();
        // ".env" matches by exact name, but a file literally named ".pem" has
        // nothing before the suffix and is refused by the name rule only if
        // listed; the suffix rule requires a non-empty stem.
        assert_eq!(
            policy.file_verdict("a.pem"),
            Some(ExclusionReason::SecretMaterial)
        );
        assert_eq!(policy.file_verdict("pem"), None);
    }

    #[test]
    fn an_operator_named_path_is_reported_as_operator_requested() {
        let policy = ExclusionPolicy::default()
            .excluding_directory("build")
            .excluding_file("notes/private.md");
        assert_eq!(
            policy.directory_verdict("build"),
            Some(ExclusionReason::OperatorRequested)
        );
        assert_eq!(
            policy.file_verdict("notes/private.md"),
            Some(ExclusionReason::OperatorRequested)
        );
        assert_eq!(policy.operator_directories(), vec!["build".to_owned()]);
        assert_eq!(policy.operator_files(), vec!["notes/private.md".to_owned()]);
    }

    #[test]
    fn the_rule_list_is_sorted_and_covers_every_table() {
        let rules = ExclusionPolicy::default().rules();
        assert!(rules.windows(2).all(|pair| pair[0] <= pair[1]));
        assert!(rules.iter().any(|(pattern, _)| pattern == "dir:.godot"));
        assert!(rules.iter().any(|(pattern, _)| pattern == "prefix:.env."));
        assert!(rules.iter().any(|(pattern, _)| pattern == "suffix:.pem"));
        assert!(
            rules
                .iter()
                .any(|(pattern, _)| pattern == "name:export_presets.cfg")
        );
    }

    #[test]
    fn every_reason_round_trips_through_its_wire_spelling() {
        for reason in ExclusionReason::ALL {
            assert_eq!(ExclusionReason::parse(reason.as_str()), Some(reason));
        }
        assert_eq!(ExclusionReason::parse("nonsense"), None);
    }
}
